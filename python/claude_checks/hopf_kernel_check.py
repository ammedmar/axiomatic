# is the reducible span exactly the ideal generated by x_k ot x_k?
n = 3
S = subsets(n)
ideal = set()
for k in range(n + 1):
    for A in S:
        for B in S:
            if k not in A and k not in B:
                ideal.add((A | {k}, B | {k}))
red = {(V, W) for V in S for W in S if V & W}
print(f"\nn={n}: ideal generated by (x_k ot x_k) == reducible span basis:", ideal == red)

# adjointness of mu and Delta: monomial (Kronecker) pairing vs socle pairing
def partitions(U):
    U = sorted(U)
    out = []
    for m in range(1 << len(U)):
        A = frozenset(u for b, u in enumerate(U) if m >> b & 1)
        out.append((A, frozenset(U) - A))
    return out

n = 2
S = subsets(n)
full = frozenset(range(n + 1))
mono_ok = socle_ok = True
for V in S:
    for W in S:
        for C in S:
            lhs_mono = 1 if (not (V & W) and (V | W) == C) else 0
            rhs_mono = sum(1 for A, B in partitions(C) if A == V and B == W) % 2
            if lhs_mono != rhs_mono:
                mono_ok = False
            lhs_soc = 1 if (not (V & W) and not ((V | W) & C) and (V | W | C) == full) else 0
            rhs_soc = sum(1 for A, B in partitions(C)
                          if not (V & A) and (V | A) == full and not (W & B) and (W | B) == full) % 2
            if lhs_soc != rhs_soc:
                socle_ok = False
print(f"\nadjointness <mu(a ot b), c> = <a ot b, Delta c>:")
print(f"  under monomial (Kronecker) pairing: {mono_ok}")
print(f"  under socle pairing <x_U,x_U'>=[U cup U'=all]: {socle_ok}")

