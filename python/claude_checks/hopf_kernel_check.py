"""Check claims about ker(mu) vs the reducible span in Lambda_n ot Lambda_n."""
from itertools import combinations

def subsets(n):
    out = []
    for r in range(n + 2):
        for S in combinations(range(n + 1), r):
            out.append(frozenset(S))
    return out

for n in range(0, 4):
    S = subsets(n)
    pairs = [(V, W) for V in S for W in S]
    red = [(V, W) for V, W in pairs if V & W]
    irr = [(V, W) for V, W in pairs if not (V & W)]
    # dim ker mu: mu surjective onto Lambda_n (dim 2^{n+1})
    dim_total, dim_lam = len(pairs), len(S)
    dim_ker = dim_total - dim_lam
    print(f"n={n}: dim(ot2)={dim_total} (4^{n+1}={4**(n+1)}), "
          f"reducible={len(red)} (4^k-3^k={4**(n+1)-3**(n+1)}), "
          f"dim ker(mu)={dim_ker} (4^k-2^k={4**(n+1)-2**(n+1)})")

